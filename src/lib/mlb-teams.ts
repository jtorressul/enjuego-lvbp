export const MLB_TEAM_BY_ID: Record<number, MlbTeamMeta> = Object.values(MLB_TEAMS).reduce(
  (acc, team) => {
    acc[team.id] = team;
    return acc;
  },
  {} as Record<number, MlbTeamMeta>
);

export function resolveMlbTeam(idOrCode?: number | string, fallbackName = "MLB Team"): MlbTeamMeta {
  if (typeof idOrCode === "number" && MLB_TEAM_BY_ID[idOrCode]) {
    return MLB_TEAM_BY_ID[idOrCode];
  }
  const num = Number(idOrCode);
  if (!Number.isNaN(num) && MLB_TEAM_BY_ID[num]) {
    return MLB_TEAM_BY_ID[num];
  }

  const raw = String(idOrCode || "").trim();
  const upper = raw.toUpperCase();
  if (MLB_TEAMS[upper]) return MLB_TEAMS[upper];
  if (upper === "OAK") return MLB_TEAMS.ATH;
  if (upper === "TBR") return MLB_TEAMS.TB;
  if (upper === "KCR") return MLB_TEAMS.KC;
  if (upper === "SDP") return MLB_TEAMS.SD;
  if (upper === "SFG") return MLB_TEAMS.SF;
  if (upper === "WSN" || upper === "WAS") return MLB_TEAMS.WSH;
  if (upper === "CHW") return MLB_TEAMS.CWS;
  if (upper === "AZ") return MLB_TEAMS.ARI;

  const lower = raw.toLowerCase();
  const found = Object.values(MLB_TEAMS).find(
    (t) =>
      t.slug === lower ||
      t.nick.toLowerCase() === lower ||
      t.name.toLowerCase().includes(lower) ||
      fallbackName.toLowerCase().includes(t.nick.toLowerCase()) ||
      fallbackName.toLowerCase().includes(t.city.toLowerCase())
  );
  return found || MLB_TEAMS.NYY;
}

export function resolveAnyBaseballTeam(
  idOrCode?: number | string,
  fallbackName = "",
  preferredLeague: "lvbp" | "mlb" = "lvbp"
): LvbpTeamMeta {
  const num = Number(idOrCode);
  if (!Number.isNaN(num) && String(idOrCode || "").trim() !== "") {
    if (MLB_TEAM_BY_ID[num]) return MLB_TEAM_BY_ID[num];
    if (num >= 690 && num <= 705) return resolveLvbpTeam(num, fallbackName);
  }
  const raw = String(idOrCode || "").trim();
  const upper = raw.toUpperCase();
  const lower = raw.toLowerCase();

  if (preferredLeague === "mlb") {
    if (MLB_TEAMS[upper]) return MLB_TEAMS[upper];
    const mlbBySlug = Object.values(MLB_TEAMS).find(
      (t) => t.slug === lower || t.nick.toLowerCase() === lower
    );
    if (mlbBySlug) return mlbBySlug;
    if (LVBP_TEAMS[upper]) return LVBP_TEAMS[upper];
    const lvbpBySlug = Object.values(LVBP_TEAMS).find(
      (t) => t.slug === lower || t.nick.toLowerCase() === lower
    );
    if (lvbpBySlug) return lvbpBySlug;
    return resolveMlbTeam(idOrCode, fallbackName);
  }

  if (LVBP_TEAMS[upper]) return LVBP_TEAMS[upper];
  if (MLB_TEAMS[upper]) return MLB_TEAMS[upper];

  const lvbpBySlug = Object.values(LVBP_TEAMS).find(
    (t) => t.slug === lower || t.nick.toLowerCase() === lower
  );
  if (lvbpBySlug) return lvbpBySlug;

  const mlbBySlug = Object.values(MLB_TEAMS).find(
    (t) =>
      t.slug === lower ||
      t.nick.toLowerCase() === lower ||
      (lower.length >= 3 && t.name.toLowerCase().includes(lower))
  );
  if (mlbBySlug) return mlbBySlug;

  return resolveLvbpTeam(idOrCode, fallbackName);
}
